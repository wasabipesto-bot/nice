for (b, s, e, t, k, p) in WINDOWS:
    l = ndig(e - 1, b); assert l == ndig(s, b)
    s2 = ndig(s * s, b); s3 = ndig(s ** 3, b)
    assert s2 == ndig((e-1)**2, b) and s3 == ndig((e-1)**3, b)
    f0 = l - t
    mid = 2
    while mid > 0 and (k + mid > s2 or b ** (k + mid - f0) >= 1 << 32 or k + mid > 12):
        mid -= 1
    k2 = k + mid
    cl = -(-s3 // 2); gl = min(5, cl - 1)
    ok_shape = b ** f0 < 1 << 31 and b ** (k2 - f0) < 1 << 31
    hw = b ** (l - min(k2, l)) > 1 << 31
    ns = set([s, s + 1, e - 1, e - 2] + [random.randrange(s, e) for _ in range(3000)])
    cnt = run_shape(b, l, s2, s3, f0, k2, 10, sorted(ns))
    print(f"b{b} [{s},{e}) t{t} k{k} p{p}: l={l} s2={s2} s3={s3} f0={f0} k2={k2} s2+s3==b:{s2+s3==b} gl={gl} H wide:{hw} shape ok:{ok_shape} n={cnt}")
