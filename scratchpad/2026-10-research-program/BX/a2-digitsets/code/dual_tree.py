"""E8: hierarchical (dual-tree) disjointness pairing inside one transversal join unit.

Unit = fixed overlap digits pi (positions [f0, k) of n), as in N1's transversal join:
 tops    = prefixes P (positions [f0, L)) with digits [f0,k) == pi, certified (cert positions >= k);
 bottoms = residues R mod b^k with digits [f0,k) == pi, certified (low k digits of n^2, n^3).
A pair (P, R) is one n = P*b^f0 + (R mod b^f0); key: n mod (b-1) is a root.
Counts (all exact, per unit):
 FLAT  = key-matched pairs (what today's join ANDs)
 IDEAL = key-matched disjoint pairs (survivors; what an output-sensitive oracle would touch)
 DUAL  = group-pair tests of a dual tree: top groups by leading j free digits (group mask = cert
         of the group's prefix interval), bottom groups by low i digits (mask = low-i cert);
         a group pair is expanded only if its masks are disjoint; schedule alternates sides;
         final level = key-matched element pairs inside surviving group pairs.
Usage: dual_tree.py b f0 k n_units seed"""
import sys, random
from nicelib import *


def main():
    b, f0, k, nunits, seed = map(int, sys.argv[1:6])
    rnd = random.Random(seed)
    lo, hi = nice_range(b)
    L = ndig(lo, b)
    t = L - f0
    o = t + k - L
    assert o >= 1
    roots = set(residues(b))
    ft = t - o          # free leading digits of a top (positions [k, L))
    fb = f0             # free low digits of a bottom (positions [0, f0))
    tot = dict(flat=0, ideal=0, dual=0, tops=0, bots=0)
    for _ in range(nunits):
        pi = rnd.randrange(b ** o)
        # tops: leading ft digits u, P = u*b^o + pi; interval [P*b^f0, (P+1)*b^f0)
        tops = []
        topgroups = {}  # (j, prefix of u) -> mask or None
        W = b ** f0
        for u in range(b ** ft):
            P = u * b ** o + pi
            a, z = max(P * W, lo), min((P + 1) * W, hi) - 1
            if a > z:
                continue
            c = [x for x in top_cert(a, z, b) if x[1] >= k]
            m = mask_of(c)
            if m is None:
                continue
            tops.append((u, P, m))
        # group masks for tops: cert of interval of all n with leading digits = prefix of u (length j)
        def tgroup_mask(j, up):
            key = (j, up)
            if key in topgroups:
                return topgroups[key]
            Wj = b ** (L - j)
            a, z = max(up * Wj, lo), min((up + 1) * Wj, hi) - 1
            if a > z:
                topgroups[key] = None
                return None
            c = [x for x in top_cert(a, z, b) if x[1] >= k]
            m = mask_of(c)
            topgroups[key] = m
            return m
        bots = []
        for v in range(b ** fb):
            R = v + pi * b ** f0
            m = mask_of(bottom_cert(R, k, b))
            if m is None:
                continue
            bots.append((v, R, m))
        tot["tops"] += len(tops)
        tot["bots"] += len(bots)
        # FLAT / IDEAL with key
        bykey = {}
        for v, R, m in bots:
            bykey.setdefault(v % (b - 1), []).append(m)
        for u, P, m in tops:
            for r in roots:
                need = (r - P) % (b - 1)
                for mb in bykey.get(need, ()):
                    tot["flat"] += 1
                    if not (m & mb):
                        tot["ideal"] += 1
        # DUAL: levels alternate: top level j = 0..ft (prefix of u has j digits => leading digits
        # of n are the j leading digits of u), bottom level i = 0..fb.
        def bgroup_mask(i, vlow):
            if i == 0:
                return 0
            return mask_of(bottom_cert(vlow, i, b))  # low i digits of n^2,n^3 from n mod b^i
        # represent group pairs as (j, uprefix, i, vlow); start (0,0,0,0)
        frontier = [(0, 0, 0, 0)]
        j = i = 0
        # tops grouped by u prefix; bottoms by v low digits
        while j < ft or i < fb:
            step_top = (j * fb <= i * ft and j < ft) or i >= fb
            final = (j + i == ft + fb - 1)
            roots_mod = roots
            new = []
            if step_top:
                j += 1
                for (_, up, _, vl) in frontier:
                    mb = bgroup_mask(i, vl)
                    for d in range(b):
                        up2 = up * b + d
                        if final and ((up2 * b ** o + pi) * 1 + vl) % (b - 1) not in roots_mod:
                            continue  # key: generated by hash, not tested
                        # top-group mask: prefix of n of length j is the leading j digits of u
                        mt = tgroup_mask(j, up2) if j > 0 else 0
                        if mt is None:
                            continue
                        tot["dual"] += 1
                        if mb is not None and not (mt & mb):
                            new.append((j, up2, i, vl))
            else:
                i += 1
                for (_, up, _, vl) in frontier:
                    mt = tgroup_mask(j, up) if j > 0 else 0
                    for d in range(b):
                        vl2 = vl + d * b ** (i - 1)
                        if final and ((up * b ** o + pi) + vl2) % (b - 1) not in roots_mod:
                            continue
                        mb = bgroup_mask(i, vl2)
                        if mb is None:
                            continue
                        tot["dual"] += 1
                        if mt is not None and not (mt & mb):
                            new.append((j, up, i, vl2))
            frontier = new
        # at the end group = single top u (j=ft) and single bottom v (i=fb); the element masks are
        # the full certificates; apply key + final element AND (counted as one more test each)
        topm = {u: m for u, P, m in tops}
        botm = {v: (R, m) for v, R, m in bots}
        for (_, u, _, v) in frontier:
            if u not in topm or v not in botm:
                continue
            tot["dual"] += 1  # element AND with full masks
            if not (topm[u] & botm[v][1]):
                tot["dual_surv"] = tot.get("dual_surv", 0) + 1
        print(f"  unit pi={pi}: tops {len(tops)} bots {len(bots)}", flush=True)
    print(f"b={b} L={L} f0={f0} k={k} t={t} o={o} units={nunits} tops={tot['tops']} bots={tot['bots']} "
          f"FLAT={tot['flat']} IDEAL={tot['ideal']} DUAL={tot['dual']} "
          f"dual_surv={tot.get('dual_surv',0)} flat/dual={tot['flat']/max(1,tot['dual']):.2f} flat/ideal={tot['flat']/max(1,tot['ideal']):.1f}")


main()
